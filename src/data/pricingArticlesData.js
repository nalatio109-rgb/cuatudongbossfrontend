// Helper tìm kiếm bài viết bảng giá theo slug hoặc query
export const getPricingArticleBySlug = (slugOrCode) => {
  if (!slugOrCode) return PRICING_ARTICLES[0];
  const clean = String(slugOrCode).toLowerCase().trim();

  // 1. Tìm chính xác trong PRICING_ARTICLES
  const found = PRICING_ARTICLES.find(
    (a) =>
      a.slug.toLowerCase() === clean ||
      a.id.toLowerCase() === clean ||
      a.brandCode.toLowerCase() === clean ||
      (a.aliases && a.aliases.some((al) => al.toLowerCase() === clean))
  );
  if (found) return found;

  // 2. Tìm kiếm tương đối theo từ khóa
  if (clean.includes("boss") || clean.includes("cd.") || clean.includes("bec.")) {
    return PRICING_ARTICLES.find((a) => a.brandCode === "bossdoor") || PRICING_ARTICLES[0];
  }
  if (clean.includes("aust")) {
    return PRICING_ARTICLES.find((a) => a.brandCode === "austdoor") || PRICING_ARTICLES[0];
  }
  if (clean.includes("door")) {
    return PRICING_ARTICLES.find((a) => a.brandCode === "doortech") || PRICING_ARTICLES[0];
  }
  if (clean.includes("tita")) {
    return PRICING_ARTICLES.find((a) => a.brandCode === "titadoor") || PRICING_ARTICLES[0];
  }
  if (clean.includes("mita")) {
    return PRICING_ARTICLES.find((a) => a.brandCode === "mitadoor") || PRICING_ARTICLES[0];
  }
  if (clean.includes("s68")) {
    return PRICING_ARTICLES.find((a) => a.brandCode === "s68") || PRICING_ARTICLES[0];
  }
  if (clean.includes("dai-loan") || clean.includes("dai loan") || clean.includes("dl-")) {
    return PRICING_ARTICLES.find((a) => a.brandCode === "dai-loan") || PRICING_ARTICLES[0];
  }
  if (clean.includes("duc") || clean.includes("ck-de")) {
    return PRICING_ARTICLES.find((a) => a.brandCode === "duc" || a.brandCode === "CK-DE") || PRICING_ARTICLES[0];
  }
  if (clean.includes("uc") || clean.includes("bd-l70")) {
    return PRICING_ARTICLES.find((a) => a.brandCode === "uc") || PRICING_ARTICLES[0];
  }

  return PRICING_ARTICLES[0];
};

